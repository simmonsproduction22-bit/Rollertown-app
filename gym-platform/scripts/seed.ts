/**
 * Seeds "Demo MMA Academy".
 *   npm run seed            → inserts into Supabase (needs SUPABASE_SERVICE_ROLE_KEY)
 *   npm run seed -- --sql   → writes supabase/seed.sql (used by `supabase db reset`)
 * Demo users are created through the Auth admin API (live) or inserted into
 * auth.users (SQL). They have no password: sign in with a magic link.
 */
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { TABLE_ORDER } from "../src/lib/seed/builder";
import { DEMO_USERS } from "../src/lib/seed/constants";
import { generateDemoDataset } from "../src/lib/seed/generate";

const IDENTITY_TABLES = new Set(["audit_log", "credit_ledger", "webhook_deliveries"]);

function sqlValue(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return `array[${v.map((x) => sqlValue(x)).join(",")}]::text[]`;
  }
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function toSql(): string {
  const data = generateDemoDataset();
  const out: string[] = ["-- Generated by scripts/seed.ts. Do not edit by hand.", "begin;"];
  for (const u of Object.values(DEMO_USERS)) {
    out.push(`insert into auth.users (id, email) values (${sqlValue(u.id)}, ${sqlValue(u.email)}) on conflict do nothing;`);
    out.push(`insert into public.profiles (id, full_name, email) values (${sqlValue(u.id)}, ${sqlValue(u.name)}, ${sqlValue(u.email)}) on conflict do nothing;`);
  }
  for (const table of TABLE_ORDER) {
    for (const row of data[table] as Record<string, unknown>[]) {
      const cols = Object.keys(row).filter((c) => !(IDENTITY_TABLES.has(table) && c === "id"));
      // Typed arrays: room_kinds is an enum array, location_ids is uuid[]
      const vals = cols.map((c) => {
        const v = row[c];
        if (c === "room_kinds" && Array.isArray(v)) return `array[${v.map(sqlValue).join(",")}]::app.room_kind[]`;
        if (c === "location_ids" && Array.isArray(v)) return `array[${v.map(sqlValue).join(",")}]::uuid[]`;
        if ((c === "plan" || c === "steps" || c === "errors" || c === "fields") && Array.isArray(v)) return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
        return sqlValue(v);
      });
      out.push(`insert into public.${table} (${cols.join(", ")}) values (${vals.join(", ")});`);
    }
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}

async function seedSupabase(): Promise<void> {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error("Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (see .env.example)");
  const admin = createClient(url, key, { auth: { persistSession: false } });
  for (const u of Object.values(DEMO_USERS)) {
    const { error } = await admin.auth.admin.createUser({ id: u.id, email: u.email, email_confirm: true, user_metadata: { full_name: u.name } } as never);
    if (error && !/already/i.test(error.message)) throw new Error(`auth user ${u.email}: ${error.message}`);
    await admin.from("profiles").upsert({ id: u.id, full_name: u.name, email: u.email });
  }
  const data = generateDemoDataset();
  for (const table of TABLE_ORDER) {
    const rows = (data[table] as Record<string, unknown>[]).map((r) => (IDENTITY_TABLES.has(table) ? { ...r, id: undefined } : r));
    for (let i = 0; i < rows.length; i += 500) {
      const { error } = await admin.from(table).insert(rows.slice(i, i + 500));
      if (error) throw new Error(`${table}: ${error.message}`);
    }
    process.stdout.write(`seeded ${table} (${rows.length})\n`);
  }
}

if (process.argv.includes("--sql")) {
  writeFileSync("supabase/seed.sql", toSql());
  process.stdout.write("wrote supabase/seed.sql\n");
} else {
  seedSupabase().catch((e: unknown) => {
    process.stderr.write(`${e instanceof Error ? e.message : String(e)}\n`);
    process.exit(1);
  });
}
